"""Phase 2: walk-forward Dixon-Coles predictions -> data/processed/predictions.parquet and
reports/phase2/model_summary.md.
PYTHONNOUSERSITE=1 conda run -n fbmodel python scripts/run_phase2.py
"""
import time

import pandas as pd

from run_phase1a import md_table, write_text  # scripts/ is on sys.path
from fbmodel.config import load_config
from fbmodel.io_guard import safe_write_path
from fbmodel.model.dixon_coles import walk_forward

INPUT_COLUMNS = ["match_id", "league", "season", "date", "home", "away", "home_goals",
                 "away_goals", "ah_line_pre", "stage"]


def main():
    cfg = load_config()
    paths = cfg["paths"]
    # Only these columns reach the model: no odds except the AH line used to price the
    # AH probabilities of the prediction (not a model input).
    m = pd.read_parquet(paths["processed"] / "matches.parquet", columns=INPUT_COLUMNS)
    t0 = time.time()
    times, parts = {}, []
    for league, g in m.groupby("league", sort=True):
        t = time.time()
        p = walk_forward(g, cfg)
        times[league] = time.time() - t
        parts.append(p)
        print(league, len(p), f"{times[league]:.1f}s", flush=True)
    pred = pd.concat(parts, ignore_index=True)
    total = time.time() - t0
    out = safe_write_path(paths["processed"] / "predictions.parquet")
    pred.to_parquet(out, index=False)

    n_pred = pred.groupby(["league", "season"]).size().rename("predictions").reset_index()
    fits = pred.drop_duplicates(["league", "fit_ref_date"])
    fit_tab = fits.groupby("league").agg(fits=("fit_ok", "size"),
                                         failed_fits=("fit_ok", lambda s: int((~s).sum()))).reset_index()
    flags = pred.groupby("league").agg(
        predictions=("match_id", "size"),
        home_few=("flag_home_few_matches", "sum"), away_few=("flag_away_few_matches", "sum"),
        with_ah_line=("ah_line", lambda s: int(s.notna().sum()))).reset_index()
    trunc = pred.groupby("league").agg(max_truncated_mass=("truncated_mass", "max"),
                                       mean_truncated_mass=("truncated_mass", "mean")).reset_index()
    ha = (pred.groupby(["league", "season"]).agg(
        home_adv_first=("home_adv", "first"), home_adv_last=("home_adv", "last"),
        home_adv_mean=("home_adv", "mean"), rho_first=("rho", "first"), rho_last=("rho", "last"),
        rho_mean=("rho", "mean")).reset_index())
    runtime = pd.DataFrame({"league": list(times), "seconds": list(times.values())})
    md = ["# Phase 2 model summary (Dixon-Coles, walk-forward)\n",
          f"Generated by scripts/run_phase2.py. Model parameters (config model): {cfg['model']}.\n"
          f"Predictions: {len(pred)} rows x {pred.shape[1]} columns. First season of each league "
          f"is training only. Refit every {cfg['model']['refit_days']} days; each block is predicted "
          f"from a fit on matches strictly before the block start.\n",
          "## Predictions per league x season\n", md_table(n_pred),
          "## Fits and failed fits (optimizer did not report success)\n", md_table(fit_tab),
          "## Flags and AH-line availability\n", md_table(flags),
          "## Truncated probability mass (score matrix 0..max_goals)\n", md_table(trunc, "{:.3e}"),
          "## Home advantage and rho per league over time (first / last / mean of the weekly fits "
          "in each season)\n", md_table(ha),
          "## Runtime\n", md_table(runtime, "{:.1f}"), f"\nTotal runtime: {total:.1f} s.\n"]
    write_text(paths["reports"] / "phase2" / "model_summary.md", "\n".join(md))
    print("predictions", pred.shape, f"total {total:.1f}s")
    print(fit_tab.to_string())
    print("max truncated mass", pred.truncated_mass.max())


if __name__ == "__main__":
    main()
