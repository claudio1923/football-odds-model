"""Generate config/column_map.yaml from the columns found in the raw snapshot.

Run: PYTHONNOUSERSITE=1 conda run -n fbmodel python scripts/make_column_map.py [snapshot_date]
Original name -> canonical name; every classified odds column is mapped or listed
under `dropped` with a reason. The file is a reviewed config artefact: re-running it
rewrites it from the raw headers.
"""
import sys
from pathlib import Path

import yaml

from fbmodel.config import load_config
from fbmodel.data.columns import classify_column
from fbmodel.data.download import RAW_SUBDIR
from fbmodel.data.read_raw import read_raw_csv
from fbmodel.io_guard import safe_write_path

ID_RESULT = {
    "Date": "date", "Time": "kickoff", "HomeTeam": "home", "Home": "home",
    "AwayTeam": "away", "Away": "away",
    "FTHG": "home_goals", "HG": "home_goals", "FTAG": "away_goals", "AG": "away_goals",
    "FTR": "result", "Res": "result",
    "HTHG": "ht_home_goals", "HTAG": "ht_away_goals", "HTR": "ht_result",
}
STATS = {
    "Attendance": "attendance", "Referee": "referee", "HS": "shots_h", "AS": "shots_a",
    "HST": "sot_h", "AST": "sot_a", "HHW": "woodwork_h", "AHW": "woodwork_a",
    "HC": "corners_h", "AC": "corners_a", "HF": "fouls_h", "AF": "fouls_a",
    "HFKC": "fkc_h", "AFKC": "fkc_a", "HO": "offsides_h", "AO": "offsides_a",
    "HY": "yellow_h", "AY": "yellow_a", "HR": "red_h", "AR": "red_a",
    "HBP": "bookpts_h", "ABP": "bookpts_a",
}
DROP_ID = {"Div": "league code is taken from the file key, not from the column",
           "Country": "league and season are taken from the file key",
           "League": "league and season are taken from the file key",
           "Season": "league and season are taken from the file key"}
SRC = {"pinnacle": "pin", "max": "max", "avg": "avg", "bet365": "b365"}
SIDE = {"H": "h", "D": "d", "A": "a", "over": "over", "under": "under",
        "home": "home", "away": "away"}
FAMILY_TAG = {"odds_1x2": "odds_1x2", "odds_ou": "odds_ou", "odds_ah": "odds_ah",
              "ah_line": "ah_line"}
# derived columns created by build_matches: canonical -> (family, timing)
DERIVED = {
    "match_id": ("id", "none"), "league": ("id", "none"), "season": ("id", "none"),
    "season_note": ("id", "none"), "stage": ("derived", "none"),
    **{f"ref_source_{m}_{t}": ("derived", "none")
       for m in ("1x2", "ou25", "ah") for t in ("pre", "close")},
    **{q: ("qa", "none") for q in (
        "qa_exact_duplicate", "qa_duplicate_key", "qa_team_twice_same_date",
        "qa_result_goals_mismatch", "qa_odds_out_of_range", "qa_overround_out_of_range")},
}


def main():
    cfg = load_config()
    snapshot = sys.argv[1] if len(sys.argv) > 1 else "2026-11-06"
    base = cfg["paths"]["raw"] / RAW_SUBDIR / snapshot
    names = []
    for f in sorted(base.glob("*.csv")):
        df, _enc = read_raw_csv(f)
        names += [c for c in df.columns if c not in names]
    mapping, dropped, avail = {}, {}, {}
    for c in names:
        k = classify_column(c)
        fam, mkt, src, tim, side = (k[x] for x in ("family", "market", "source", "timing", "side"))
        if fam == "unclassified":
            raise SystemExit(f"unclassified column: {c}")
        if c in ID_RESULT:
            canon = ID_RESULT[c]
            mapping[c] = canon
            avail[canon] = ("result" if fam == "result" else "id", "none")
        elif c in STATS:
            mapping[c] = STATS[c]
            avail[STATS[c]] = ("match_stats", "none")
        elif c in DROP_ID:
            dropped[c] = DROP_ID[c]
        elif fam == "other":
            dropped[c] = "bookmaker-count helper (Betbrain); not used"
        elif fam in FAMILY_TAG:
            if src in SRC:
                if fam == "ah_line":
                    canon = ("ah_line" if src == "market" else f"ah_line_{SRC[src]}") + f"_{tim}"
                else:
                    canon = f"odds_{mkt}_{SRC[src]}_{tim}_{SIDE[side]}"
                mapping[c] = canon
                avail[canon] = (fam, tim)
            elif src == "market":
                canon = f"ah_line_{tim}"
                mapping[c] = canon
                avail[canon] = (fam, tim)
            else:
                dropped[c] = ("bookmaker outside the analysis set (Pinnacle, Max, Avg, Bet365); "
                              "kept in the raw files only")
        else:
            raise SystemExit(f"unhandled column: {c} {k}")
    for canon, (fam, tim) in DERIVED.items():
        avail[canon] = (fam, tim)
    out = {
        "map": dict(sorted(mapping.items())),
        "dropped": dict(sorted(dropped.items())),
        "availability": {c: {"family": f, "timing": t} for c, (f, t) in sorted(avail.items())},
    }
    p = safe_write_path(cfg["paths"]["raw"].parents[1] / "config" / "column_map.yaml")
    p.write_text("# Generated by scripts/make_column_map.py from the raw headers.\n"
                 + yaml.safe_dump(out, sort_keys=False, width=100), encoding="utf-8")
    print(len(mapping), "mapped,", len(dropped), "dropped,", len(avail), "canonical/derived")


if __name__ == "__main__":
    main()
